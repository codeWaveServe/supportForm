function applyTranslation(language) {
    const userLanguage = language || navigator.language.split('-')[0];
    const content = translations[userLanguage] || translations.en;

    document.getElementById("title").innerHTML = content.title;
    document.getElementById("info-collect").innerHTML = `<b>${content["info-collect"]}</b><br /><span>${content["info-collect-span"]}</span>`;
    document.getElementById("use-cookies").innerHTML = `<b>${content["use-cookies"]}</b><br /><span>${content["use-cookies-span"]}</span>`;
    document.getElementById("info-disclosure").innerHTML = `<b>${content["info-disclosure"]}</b><br /><span>${content["info-disclosure-span"]}</span>`;
    document.getElementById("ads").innerHTML = `<b>${content.ads}</b><br /><span>${content["ads-span"]}</span>`;
    document.getElementById("consent").innerHTML = `<b>${content.consent}</b><br /><span>${content["consent-span"]}</span>`;
    document.getElementById("changes").innerHTML = `<b>${content.changes}</b><br /><span>${content["changes-span"]}</span>`;
    document.getElementById("contact").innerHTML = `<b>${content.contact}</b><br /><span>${content["contact-span"]}</span>`;
    document.getElementById("browser-language").innerHTML += userLanguage;
}
